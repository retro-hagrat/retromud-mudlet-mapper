#!/usr/bin/env python3
"""Stitch src/*.lua -> dist/retromud-mapper.{lua,xml,mpackage}, with sanity checks."""
import glob, json, os, re, shutil, subprocess, sys, zipfile
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(ROOT, "dist")

# comments and strings, in scan order, so banned tokens inside them are ignored
STRIP = re.compile(
    r"--\[(=*)\[.*?\]\1\]|--[^\n]*|\[(=*)\[.*?\]\2\]"
    r'|"(?:\\.|[^"\\\n])*"' r"|'(?:\\.|[^'\\\n])*'", re.S)
BANNED = [
    (r"\bgoto\b", "goto"), (r"//", "// integer division"),
    (r"<<|>>", "bit shift"), (r"[&|]", "bitwise & or |"),
    (r"~(?!=)", "bitwise ~"), (r"\btable\.unpack\b", "table.unpack"),
    (r"\butf8\b", "utf8"),
    (r"<(?:const|close)>", "<const>/<close> attrib"), (r"::\w+::", "label"),
    (r"\b(?:math\.(?:type|tointeger|ult)|table\.(?:pack|move)"
     r"|string\.(?:pack|unpack|packsize)|rawlen|warn)\b", "5.2+ library"),
    (r"\bload\s*\(", "load"), (r"\b0[xX][0-9a-fA-F.]*[pP]", "hex float"),
]
# string escapes are invisible after STRIP, so check the raw body
ESCAPE = re.compile(r"(?<!\\)\\[xzu]")

def lint(body):
    code = STRIP.sub(" ", body)
    found = ["line %d: banned %s" % (code[:m.start()].count("\n") + 1, what)
             for pat, what in BANNED for m in re.finditer(pat, code)]
    return found + ["line %d: banned \\x/\\z/\\u escape" % (body[:m.start()].count("\n") + 1)
                    for m in ESCAPE.finditer(body)]

def find_lua():
    lua = os.environ.get("LUA") or shutil.which("lua")
    if not lua:
        sys.exit("build: no lua binary (set LUA=/path/to/lua)")
    return lua

def lua_check(path):
    r = subprocess.run([find_lua(), os.path.join(ROOT, "test", "check_body.lua"), path],
                       capture_output=True, text=True)
    return [] if r.returncode == 0 else [(r.stdout + r.stderr).strip()]

def lua_value(file, name):
    m = re.search(name + r'\s*=\s*(?:\[\[|")([^\]"]+)', open(file).read())
    return m and m.group(1)

def seed_index():
    """(Lua source, problems): rmap.seedIndex maps each seed's start-room
    fingerprint (the one room with userData start = "1") to its name."""
    idx, problems = {}, []
    for p in sorted(glob.glob(os.path.join(ROOT, "seeds", "*.json"))):
        name = os.path.basename(p)[:-5]
        rooms = [r for a in json.load(open(p))["areas"]
                 for r in a.get("rooms", [])
                 if r.get("userData", {}).get("start") == "1"]
        fp = rooms[0].get("userData", {}).get("fp", "") if rooms else ""
        if len(rooms) != 1 or not fp.isascii() or not fp:
            problems.append("seed %s: needs exactly one start room with an ascii fp" % name)
        elif fp in idx:
            problems.append("seed %s: start fingerprint %r already used by %s" % (name, fp, idx[fp]))
        else:
            idx[fp] = name
    lines = ["rmap.seedIndex = {"] + ["    [%s] = %s," % (json.dumps(k), json.dumps(v))
                                      for k, v in sorted(idx.items())] + ["}"]
    return "\n".join(lines) + "\n", problems

def lua_str(v):
    """A Lua string literal; seeds are plain ASCII so JSON escapes are valid Lua."""
    assert v.isascii(), "non-ascii text in a seed: %r" % v
    return json.dumps(v)

def seed_data():
    """(Lua source, problems): rmap.seedData holds every seed's rooms so the
    package can merge them into the player's map (45_seed). One room is
    {id, name, x, y, z, {dir = toId}, {stub dirs}, {userData}}."""
    areas, problems = [], []
    for p in sorted(glob.glob(os.path.join(ROOT, "seeds", "*.json"))):
        name = os.path.basename(p)[:-5]
        try:
            area = [a for a in json.load(open(p))["areas"] if a.get("rooms")]
            assert len(area) == 1, "needs exactly one area with rooms"
            rooms = []
            for r in area[0]["rooms"]:
                x, y, z = r["coordinates"]
                ex = ", ".join("[%s] = %d" % (lua_str(e["name"]), e["exitId"]) for e in r["exits"])
                st = ", ".join(lua_str(e["name"]) for e in r.get("stubExits", []))
                ud = ", ".join("[%s] = %s" % (lua_str(k), lua_str(v)) for k, v in sorted(r["userData"].items()))
                rooms.append("        {%d, %s, %d, %d, %d, {%s}, {%s}, {%s}}," % (
                    r["id"], lua_str(r["name"]), x, y, z, ex, st, ud))
            areas.append("    [%s] = { area = %s, rooms = {\n%s\n    } }," % (
                lua_str(name), lua_str(area[0]["name"]), "\n".join(rooms)))
        except (AssertionError, KeyError) as e:
            problems.append("seed %s: %s" % (name, e))
    return "rmap.seedData = {\n" + "\n".join(areas) + "\n}\n", problems

def main():
    files = sorted(glob.glob(os.path.join(ROOT, "src", "*.lua")))
    body = "\n".join(open(f).read() for f in files)
    index_src, seed_problems = seed_index()
    data_src, data_problems = seed_data()
    seed_problems += data_problems
    body += "\n-- generated by build.py from seeds/*.json\n" + index_src + data_src
    os.makedirs(DIST, exist_ok=True)
    body_path = os.path.join(DIST, "retromud-mapper.lua")
    open(body_path, "w").write(body)

    problems = seed_problems + lint(body) + lua_check(body_path)
    cfg = os.path.join(ROOT, "config.lua")
    m = re.search(r'rmap\.version\s*=\s*"([^"]+)"', body)
    if not m or m.group(1) != lua_value(cfg, "version"):
        problems.append("rmap.version does not match config.lua version")
    if problems:
        print("build FAILED:\n  " + "\n  ".join(problems))
        sys.exit(1)

    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE MudletPackage>\n'
           '<MudletPackage version="1.001">\n<ScriptPackage>\n'
           '<Script isActive="yes" isFolder="no">\n<name>retromud-mapper</name>\n'
           '<packageName></packageName>\n<script>%s</script>\n'
           '<eventHandlerList />\n</Script>\n</ScriptPackage>\n</MudletPackage>\n'
           % escape(body))
    open(os.path.join(DIST, "retromud-mapper.xml"), "w").write(xml)
    out = os.path.join(DIST, "retromud-mapper.mpackage")
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(DIST, "retromud-mapper.xml"), "retromud-mapper.xml")
        z.write(cfg, "config.lua")
    print("built %s (%d modules, checks passed)" % (out, len(files)))

if __name__ == "__main__":
    main()
